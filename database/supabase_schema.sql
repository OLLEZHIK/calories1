DROP POLICY IF EXISTS "Allow anon read/write meal_items" ON public.meal_items;
DROP POLICY IF EXISTS "Allow anon read/write product_prices" ON public.product_prices;
DROP POLICY IF EXISTS "Allow anon read/write coach_recommendations" ON public.coach_recommendations;
DROP POLICY IF EXISTS "Allow anon read/write user_goals" ON public.user_goals;
DROP POLICY IF EXISTS "Allow anon read/write custom_products" ON public.custom_products;
DROP POLICY IF EXISTS "Allow anon read/write bot_sessions" ON public.bot_sessions;
